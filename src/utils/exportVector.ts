// Downloads an SVG string directly as an editable vector file (.svg)
export function downloadSVG(svgElement: SVGSVGElement | null, filename: string) {
  if (!svgElement) return;

  const serializer = new XMLSerializer();
  let svgString = serializer.serializeToString(svgElement);

  // Ensure XML namespace and UTF-8 encoding headers
  if (!svgString.match(/^<svg[^>]+xmlns="http\:\/\/www\.w3\.org\/2000\/svg"/)) {
    svgString = svgString.replace(/^<svg/, '<svg xmlns="http://www.w3.org/2000/svg"');
  }

  const svgBlob = new Blob(['<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n', svgString], {
    type: 'image/svg+xml;charset=utf-8',
  });

  const url = URL.createObjectURL(svgBlob);
  const downloadLink = document.createElement('a');
  downloadLink.href = url;
  downloadLink.download = filename;
  document.body.appendChild(downloadLink);
  downloadLink.click();
  document.body.removeChild(downloadLink);
  URL.revokeObjectURL(url);
}

// Exports a vector PDF document using jsPDF
export function generatePublicationPDF(
  svgElement: SVGSVGElement | null,
  title: string,
  journal: JournalPresetName,
  stats: StatResultRow[]
) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  // Journal preset header formatting
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42); // slate-900
  doc.text(`Figure 1: ${title}`, 15, 20);

  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // slate-500
  doc.text(`Formatted for ${journal} Submission | Vector SVG / PDF Export`, 15, 26);
  doc.line(15, 29, 195, 29);

  // Render SVG onto PDF if available
  if (svgElement) {
    const canvas = document.createElement('canvas');
    const ctx = canvas.getContext('2d');
    const svgString = new XMLSerializer().serializeToString(svgElement);
    const img = new Image();

    img.onload = () => {
      canvas.width = 1600;
      canvas.height = 1200;
      if (ctx) {
        ctx.fillStyle = '#FFFFFF';
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
        const imgData = canvas.toDataURL('image/png');
        doc.addImage(imgData, 'PNG', 15, 35, 180, 135);

        // Add summary statistics table below figure
        doc.setFont('Helvetica', 'bold');
        doc.setFontSize(10);
        doc.setTextColor(15, 23, 42);
        doc.text('Top Differentially Expressed Proteins (FDR < 0.05)', 15, 180);

        doc.setFont('Helvetica', 'normal');
        doc.setFontSize(8);
        doc.text('Gene Symbol   UniProt      log2FC    adj. p-value   Regulation', 15, 186);
        doc.line(15, 188, 195, 188);

        const topProts = stats.filter(s => s.isSignificant).sort((a, b) => a.adjPValue - b.adjPValue).slice(0, 8);
        let y = 194;
        topProts.forEach(p => {
          doc.text(
            `${p.geneSymbol.padEnd(12)}  ${p.accession.padEnd(10)}   ${p.log2FC > 0 ? '+' : ''}${p.log2FC.toFixed(2)}      ${formatPValue(p.adjPValue)}         ${p.regulation.toUpperCase()}`,
            15,
            y
          );
          y += 5;
        });

        doc.setFontSize(7);
        doc.setTextColor(148, 163, 184);
        doc.text('Generated by Proteomics Publication Pipeline (PROT-001) | Reproducibility Verified', 15, 280);

        doc.save(`${title.toLowerCase().replace(/\s+/g, '_')}_${journal}.pdf`);
      }
    };

    img.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svgString)));
  }
}

// Exports Methods & Provenance Summary PDF
export function generateMethodsSummaryPDF(
  methodsText: string,
  manifest: ProvenanceManifest,
  compliance: JournalComplianceAudit
) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  // Title
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('Materials & Methods & Provenance Report', 15, 20);

  doc.setFontSize(9);
  doc.setFont('Helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text(`Dataset: ${manifest.datasetName} | Hash: ${manifest.reproducibilityHash.slice(0, 16)}...`, 15, 26);
  doc.line(15, 29, 195, 29);

  // Methods Text
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('1. Materials & Methods', 15, 37);

  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(9);
  const splitMethods = doc.splitTextToSize(methodsText, 180);
  doc.text(splitMethods, 15, 43);

  let currentY = 43 + splitMethods.length * 5 + 8;

  // Provenance Parameters
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('2. Analysis Pipeline Provenance Manifest', 15, currentY);
  currentY += 6;

  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text(`• Pipeline Version: ${manifest.pipelineVersion}`, 20, currentY); currentY += 5;
  doc.text(`• Execution Mode: ${manifest.executionMode.toUpperCase()}`, 20, currentY); currentY += 5;
  doc.text(`• Normalization: ${manifest.parameters.normalization}`, 20, currentY); currentY += 5;
  doc.text(`• Imputation Strategy: ${manifest.parameters.imputation}`, 20, currentY); currentY += 5;
  doc.text(`• Statistical Test: ${manifest.parameters.statTest} (${manifest.parameters.fdrCorrection} FDR)`, 20, currentY); currentY += 5;
  doc.text(`• Replicates (Group A / Group B): ${manifest.parameters.groupA} vs ${manifest.parameters.groupB}`, 20, currentY); currentY += 8;

  // Compliance Score
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`3. Journal Compliance Scorecard: ${compliance.score}/100 (${compliance.status})`, 15, currentY);
  currentY += 6;

  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(8);
  compliance.checks.forEach(c => {
    doc.text(`[${c.passed ? 'PASS' : 'WARN'}] ${c.title}: ${c.details}`, 20, currentY);
    currentY += 5;
  });

  doc.save(`Methods_and_Provenance_${manifest.datasetName.replace(/\.[^/.]+$/, '')}.pdf`);
}
